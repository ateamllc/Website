const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const sourceFiles = [
  'css/partials/nav.css',
  'css/partials/hero.css',
  'css/partials/email-prompt.css',
  'css/partials/footer.css',
  'css/partials/hiring-banner.css',
  'css/components.css',
  'css/main.css',
  'css/pages/home.css',
];

const importPattern = /^@import\s+url\([^)]+\);\s*$/gm;
const sections = sourceFiles.map((relativePath) => {
  const absolutePath = path.join(rootDir, relativePath);
  let css = fs.readFileSync(absolutePath, 'utf8');
  if (relativePath === 'css/main.css') {
    css = css.replace(importPattern, '').trimStart();
  }
  return `/* Source: ${relativePath} */\n${css.trim()}\n`;
});

const banner = [
  '/* Generated by scripts/generate-home-css.js.',
  '   Edit the source stylesheets, then regenerate this bundle. */',
  '',
].join('\n');

const outputPath = path.join(rootDir, 'css/home.bundle.css');
fs.writeFileSync(outputPath, banner + sections.join('\n'), 'utf8');
console.log(`Wrote ${outputPath}`);

const criticalPath = path.join(rootDir, 'css/pages/home-critical.css');
const indexPath = path.join(rootDir, 'index.html');
const criticalStart = '    <!-- BEGIN GENERATED HOME CRITICAL CSS -->';
const criticalEnd = '    <!-- END GENERATED HOME CRITICAL CSS -->';
const criticalCss = fs.readFileSync(criticalPath, 'utf8').trim();
const indexHtml = fs.readFileSync(indexPath, 'utf8');
const startIndex = indexHtml.indexOf(criticalStart);
const endIndex = indexHtml.indexOf(criticalEnd);

if (startIndex === -1 || endIndex === -1 || endIndex < startIndex) {
  throw new Error('Unable to find generated home critical CSS markers in index.html');
}

const criticalBlock = [
  criticalStart,
  '    <style>',
  '/* Generated by scripts/generate-home-css.js from css/pages/home-critical.css. */',
  criticalCss,
  '    </style>',
  criticalEnd,
].join('\n');
const nextIndexHtml = indexHtml.slice(0, startIndex)
  + criticalBlock
  + indexHtml.slice(endIndex + criticalEnd.length);
fs.writeFileSync(indexPath, nextIndexHtml, 'utf8');
console.log(`Inlined ${criticalPath} into ${indexPath}`);
