const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const sourceFiles = [
  'css/partials/nav.css',
  'css/partials/hero.css',
  'css/partials/email-prompt.css',
  'css/partials/footer.css',
  'css/partials/hiring-banner.css',
  'css/components.css',
  'css/main.css',
  'css/pages/home.css',
];

const importPattern = /^@import\s+url\([^)]+\);\s*$/gm;
const sections = sourceFiles.map((relativePath) => {
  const absolutePath = path.join(rootDir, relativePath);
  let css = fs.readFileSync(absolutePath, 'utf8');
  if (relativePath === 'css/main.css') {
    css = css.replace(importPattern, '').trimStart();
  }
  return `/* Source: ${relativePath} */\n${css.trim()}\n`;
});

const banner = [
  '/* Generated by scripts/generate-home-css.js.',
  '   Edit the source stylesheets, then regenerate this bundle. */',
  '',
].join('\n');

const outputPath = path.join(rootDir, 'css/home.bundle.css');
fs.writeFileSync(outputPath, banner + sections.join('\n'), 'utf8');
console.log(`Wrote ${outputPath}`);
