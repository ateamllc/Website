const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

// Resolve imports in place so that the original cascade order is preserved.
function flattenCss(filename, rootDir, parents = []) {
  if (parents.includes(filename)) throw new Error(`Circular CSS import: ${filename}`);
  const relative = path.relative(rootDir, filename);
  if (relative.startsWith('..') || path.isAbsolute(relative)) throw new Error(`CSS outside site: ${filename}`);
  let css = fs.readFileSync(filename, 'utf8');
  // Asset URLs must keep pointing to their original location after bundling.
  css = css.replace(/url\(\s*(["']?)([^)"']+)\1\s*\)/g, (match, quote, value) => {
    if (/^(?:\/|#|[a-z][a-z\d+.-]*:)/i.test(value)) return match;
    const base = new URL(relative.replaceAll(path.sep, '/'), 'https://site.invalid/');
    const target = new URL(value.trim(), base);
    return `url("${target.pathname}${target.search}${target.hash}")`;
  });
  css = css.replace(/^\s*@import\s+url\(["']([^"']+)["']\);[^\S\r\n]*$/gm, (_, imported) => {
    if (!imported.startsWith('/') || imported.startsWith('//') || /[?#]/.test(imported)) {
      throw new Error(`Unsupported CSS import: ${imported}`);
    }
    return flattenCss(path.join(rootDir, imported.slice(1)), rootDir, [...parents, filename]);
  });
  if (/@import\b/i.test(css)) throw new Error(`Unresolved CSS import in ${filename}`);
  return css;
}

function generate(rootDir = path.resolve(__dirname, '..')) {
  const css = '/* Generated by scripts/generate-main-css.js. Edit source CSS and regenerate. */\n'
    + flattenCss(path.join(rootDir, 'css/main.css'), rootDir);
  fs.writeFileSync(path.join(rootDir, 'css/main.bundle.css'), css);
  const version = crypto.createHash('sha256').update(css).digest('hex').slice(0, 12);
  let count = 0;
  function visit(dir) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      if (entry.name.startsWith('.') || ['node_modules', 'docs', 'tests'].includes(entry.name)) continue;
      const filename = path.join(dir, entry.name);
      if (entry.isDirectory()) visit(filename);
      else if (entry.name.endsWith('.html')) {
        const before = fs.readFileSync(filename, 'utf8');
        const after = before.replace(/(href=["'])\/css\/main(?:\.bundle)?\.css(?:\?[^"']*)?(["'])/g,
          `$1/css/main.bundle.css?v=${version}$2`);
        if (after !== before) { fs.writeFileSync(filename, after); count++; }
      }
    }
  }
  visit(rootDir);
  console.log(`Generated main.bundle.css (${Buffer.byteLength(css)} bytes); updated ${count} HTML files.`);
}

if (require.main === module) generate();
module.exports = { flattenCss, generate };
